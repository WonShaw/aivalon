// 没被 AI 占用的头像，人类玩家默认依次用这些（也可以选任何一个）
const SPARE_AVATARS = AVATARS.map((a) => a.id).filter((id) => !Object.values(AI_AVATARS).includes(id));

export function defaultHumanAvatar(index: number): string {
  return SPARE_AVATARS[index % SPARE_AVATARS.length];
}

// 玩家的头像。早期的对局记录没有保存头像：AI 按名字找，人类按座位给一个
export function avatarOf(p: PlayerInfo): string {
  if (p.avatar && BY_ID.has(p.avatar)) return p.avatar;
  if (p.kind === 'ai' && AI_AVATARS[p.name]) return AI_AVATARS[p.name];
  return defaultHumanAvatar(p.seat - 1);
}
